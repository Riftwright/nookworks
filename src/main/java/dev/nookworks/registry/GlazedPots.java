package dev.nookworks.registry;

import java.util.ArrayList;
import java.util.List;

import dev.nookworks.Nookworks;
import dev.nookworks.furniture.HangingPlanterBlock;
import dev.nookworks.furniture.TrailingPlantBlock;
import net.minecraft.core.BlockPos;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.sounds.SoundSource;
import net.minecraft.util.RandomSource;
import net.minecraft.world.attribute.EnvironmentAttributes;
import net.minecraft.world.item.BlockItem;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.EyeblossomBlock;
import net.minecraft.world.level.block.FlowerPotBlock;
import net.minecraft.world.level.block.SoundType;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.material.MapColor;
import net.minecraft.world.level.material.PushReaction;
import net.neoforged.neoforge.registries.DeferredBlock;
import net.neoforged.neoforge.registries.DeferredItem;

/**
 * Glazed Flower Pot: the flower pot in cream glaze. It holds everything a vanilla pot holds, and our Dawnwood
 * sapling: every vanilla potted block gets a glazed twin, {@code glazed_potted_<plant>}, named like the vanilla one.
 * Planting and taking the plant out are the vanilla pot's own code - NeoForge links each full pot to its empty one.
 * <p>
 * The models are generated by {@code tools/gen_glazed_pots.py} from vanilla's potted models: the plant is kept, the
 * pot is swapped for the glazed one.
 */
public final class GlazedPots {
    public static final DeferredBlock<FlowerPotBlock> EMPTY = ModBlocks.BLOCKS.registerBlock("glazed_flower_pot",
            FlowerPotBlock::new, GlazedPots::properties);
    public static final DeferredItem<BlockItem> ITEM = ModItems.ITEMS.registerSimpleBlockItem(EMPTY);

    /** The strands each hanging planter grows down below itself. */
    public static final DeferredBlock<TrailingPlantBlock> TRAIL_GREEN = trail("hanging_planter_green_trail");
    public static final DeferredBlock<TrailingPlantBlock> TRAIL_PINK = trail("hanging_planter_pink_trail");

    /** Hanging planters, one per plant: the glazed bowl on cords, green trailing leaves or pink ones. */
    public static final DeferredBlock<HangingPlanterBlock> HANGING_GREEN = hanging("hanging_planter_green");
    public static final DeferredBlock<HangingPlanterBlock> HANGING_PINK = hanging("hanging_planter_pink");
    public static final DeferredItem<BlockItem> HANGING_GREEN_ITEM = ModItems.ITEMS.registerSimpleBlockItem(HANGING_GREEN);
    public static final DeferredItem<BlockItem> HANGING_PINK_ITEM = ModItems.ITEMS.registerSimpleBlockItem(HANGING_PINK);

    private static DeferredBlock<HangingPlanterBlock> hanging(String name) {
        return ModBlocks.BLOCKS.registerBlock(name, HangingPlanterBlock::new,
                p -> properties(p).mapColor(MapColor.PLANT).randomTicks());
    }

    private static DeferredBlock<TrailingPlantBlock> trail(String name) {
        return ModBlocks.BLOCKS.registerBlock(name, TrailingPlantBlock::new,
                p -> p.mapColor(MapColor.PLANT).noCollision().instabreak().replaceable()
                        .noLootTable().sound(SoundType.VINE).pushReaction(PushReaction.POPPED).ignitedByLava());
    }

    /** The strands the given hanging planter grows. */
    public static TrailingPlantBlock trailOf(Block planter) {
        return planter == HANGING_PINK.get() ? TRAIL_PINK.get() : TRAIL_GREEN.get();
    }

    /** Every glazed pot with a plant in it. */
    public static final List<DeferredBlock<FlowerPotBlock>> FULL = new ArrayList<>();

    static {
        // Vanilla's blocks are all registered before any mod is built, so its pots can be read off the registry here.
        for (Block block : BuiltInRegistries.BLOCK) {
            if (block instanceof FlowerPotBlock pot && pot.getEmptyPot() == Blocks.FLOWER_POT && pot.getPotted() != Blocks.AIR
                    && BuiltInRegistries.BLOCK.getKey(block).getNamespace().equals("minecraft")) {
                String path = BuiltInRegistries.BLOCK.getKey(block).getPath();
                Block plant = pot.getPotted();
                boolean eyeblossom = plant == Blocks.OPEN_EYEBLOSSOM || plant == Blocks.CLOSED_EYEBLOSSOM;
                FULL.add(ModBlocks.BLOCKS.registerBlock("glazed_" + path,
                        p -> eyeblossom ? new EyeblossomPot(plant, plant == Blocks.OPEN_EYEBLOSSOM, p) : new FlowerPotBlock(EMPTY, () -> plant, p),
                        p -> properties(p).overrideDescription(block.getDescriptionId())));
            }
        }
        FULL.add(ModBlocks.BLOCKS.registerBlock("glazed_potted_dawnwood_sapling",
                p -> new FlowerPotBlock(EMPTY, ModWoods.DAWNWOOD_SAPLING, p),
                p -> properties(p).overrideDescription("block.nookworks.potted_dawnwood_sapling")));
    }

    /**
     * A glazed pot with an eyeblossom in it opens at dusk and closes at dawn, as one in a clay pot does: vanilla's own
     * pot turns only its own blocks, by name, and a glazed one stayed as it was planted.
     */
    static final class EyeblossomPot extends FlowerPotBlock {
        private final boolean open;

        EyeblossomPot(Block plant, boolean open, BlockBehaviour.Properties properties) {
            super(EMPTY, () -> plant, properties);
            this.open = open;
        }

        @Override
        protected boolean isRandomlyTicking(BlockState state) {
            return true;
        }

        @Override
        protected void randomTick(BlockState state, ServerLevel level,
                BlockPos pos, RandomSource random) {
            boolean shouldBeOpen = level.environmentAttributes().getValue(EnvironmentAttributes.EYEBLOSSOM_OPEN, pos)
                    .toBoolean(this.open);
            if (this.open != shouldBeOpen) {
                Block other = BuiltInRegistries.BLOCK.getValue(Nookworks.id(this.open ? "glazed_potted_closed_eyeblossom" : "glazed_potted_open_eyeblossom"));
                level.setBlock(pos, other.defaultBlockState(), Block.UPDATE_ALL);
                var turned = EyeblossomBlock.Type.fromBoolean(this.open).transform();
                turned.spawnTransformParticle(level, pos, random);
                level.playSound(null, pos, turned.longSwitchSound(), SoundSource.BLOCKS, 1.0F, 1.0F);
            }
        }
    }

    private static BlockBehaviour.Properties properties(BlockBehaviour.Properties p) {
        return p.instabreak().noOcclusion().pushReaction(PushReaction.POPPED).sound(SoundType.DECORATED_POT);
    }

    /** Loads this class, so its blocks are registered with the rest. */
    public static void init() {
        Nookworks.LOGGER.debug("{} glazed pots", FULL.size() + 1);
    }

    private GlazedPots() {}
}
